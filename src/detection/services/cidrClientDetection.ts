export type ClientType =
  | "PC" | "DOCOMO_M" | "DOCOMO_F" | "SOFTBANK_M" | "SOFTBANK_F"
  | "AU_M" | "AU_F" | "EMOBILE_M" | "EMOBILE_F" | "WILLCOM_M" | "WILLCOM_F"
  | "IBIS" | "JIG" | "IPHONE_F" | "IPHONE_WIFI" | "P2" | "OPERAMINI" | "FULLBROWSER";

const ipToBinary = (ip: string): Buffer | null => {
  try {
    if (ip.includes(":")) {
      const parts = ip.split("::");
      const left = parts[0] ? parts[0].split(":") : [];
      const right = parts[1] ? parts[1].split(":") : [];
      const missing = 8 - left.length - right.length;
      const zeros = Array(missing).fill("0");
      const expanded = [...left, ...zeros, ...right].map(s => s.padStart(4, "0")).join(":");
      return Buffer.from(expanded.replace(/:([0-9a-fA-F]{1,4})/g, (_, h) => {
        return Buffer.from(h.padStart(4, "0"), "hex").toString("binary");
      }).replace(/^([0-9a-fA-F]{4})/, (_, h) => Buffer.from(h, "hex").toString("binary")), "binary");
    }
    const octets = ip.split(".").map(Number);
    return Buffer.from(octets);
  } catch {
    return null;
  }
};

const cidrHit = (cidrList: string[], ip: string): boolean => {
  const ipBin = ipToBinary(ip);
  if (!ipBin) return false;

  for (const entry of cidrList) {
    let cidr = entry;
    if (!cidr.includes("/")) cidr += "/32";
    const [target, lengthStr] = cidr.split("/");
    const prefixLength = parseInt(lengthStr, 10);
    const targetBin = ipToBinary(target);
    if (!targetBin) continue;

    const byteLen = Math.ceil(prefixLength / 8);
    for (let i = 0; i < byteLen; i++) {
      if (i === byteLen - 1 && prefixLength % 8 !== 0) {
        const mask = 0xFF << (8 - (prefixLength % 8));
        if ((ipBin[i] & mask) !== (targetBin[i] & mask)) break;
      } else {
        if (ipBin[i] !== targetBin[i]) break;
      }
      if (i === byteLen - 1) return true;
    }
    if (byteLen === 0) return true;
  }
  return false;
};

export const detectClientByCidr = (ip: string, userAgent: string, hostname: string): ClientType => {
  if (cidrHit(CARRIER_CIDRS.docomo, ip)) return "DOCOMO_M";
  if (cidrHit(CARRIER_CIDRS.docomo_pc, ip)) return "DOCOMO_F";
  if (cidrHit(CARRIER_CIDRS.vodafone, ip)) return "SOFTBANK_M";
  if (cidrHit(CARRIER_CIDRS.vodafone_pc, ip)) return "SOFTBANK_F";
  if (cidrHit(CARRIER_CIDRS.ezweb, ip)) return "AU_M";
  if (cidrHit(CARRIER_CIDRS.ezweb_pc, ip)) return "AU_F";
  if (cidrHit(CARRIER_CIDRS.emobile, ip)) {
    if (/^emobile\/1\.0\.0/.test(userAgent)) return "EMOBILE_M";
    return "EMOBILE_F";
  }
  if (cidrHit(CARRIER_CIDRS.willcom, ip)) {
    if (/^Mozilla\/3\.0/.test(userAgent)) return "WILLCOM_M";
    if (/^Mozilla\/4\.0/.test(userAgent) && /IEMobile|PPC/.test(userAgent)) return "WILLCOM_M";
    return "WILLCOM_F";
  }
  if (cidrHit(CARRIER_CIDRS.ibis, ip)) return "IBIS";
  if (cidrHit(CARRIER_CIDRS.jig, ip)) return "JIG";
  if (cidrHit(CARRIER_CIDRS.iphone, ip)) return "IPHONE_F";
  if (cidrHit(CARRIER_CIDRS.p2, ip)) return "P2";
  if (/\.opera-mini\.net$/.test(hostname)) return "OPERAMINI";
  if (/ iPhone| iPad/.test(userAgent)) return "IPHONE_WIFI";
  return "PC";
};

export const getProductInfo = (clientType: ClientType, headers: Record<string, string>): string => {
  switch (clientType) {
    case "DOCOMO_M":
    case "DOCOMO_F": {
      const guid = headers["x-dcmguid"] || "";
      return guid.replace(/^X-DCMGUID:\s*([a-zA-Z0-9]+)$/i, "$1");
    }
    case "SOFTBANK_M":
    case "SOFTBANK_F": {
      const ua = headers["user-agent"] || "";
      const match = ua.match(/\/SN([A-Za-z0-9]+)\s/);
      return match ? match[1] : "";
    }
    case "AU_M":
    case "AU_F": {
      const subno = headers["x-up-subno"] || "";
      const match = subno.match(/([A-Za-z0-9_]+)\.ezweb\.ne\.jp/i);
      return match ? match[1] : "";
    }
    case "EMOBILE_M":
    case "EMOBILE_F": {
      const emUid = headers["x-em-uid"] || "";
      return emUid.replace(/x-em-uid:\s*(.+)/i, "$1");
    }
    case "P2": {
      const serial = headers["x-p2-mobile-serial-bbm"] || "";
      if (serial) return serial;
      const ua = headers["user-agent"] || "";
      const match = ua.match(/p2-user-hash:\s*(.+)\)/i);
      return match ? match[1] : headers["remote-host"] || "";
    }
    default:
      return headers["remote-host"] || "";
  }
};
